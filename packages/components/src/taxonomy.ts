/** Stable subcategory id from its name ("Metal sheets and plates" → "metal-sheets-and-plates"). */
export const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const cat = (
  number: number,
  id: ComponentCategoryId,
  name: string,
  icon: string,
  description: string,
  subs: string[],
): Category => ({
  id,
  number,
  name,
  icon,
  description,
  subcategories: subs.map((n) => ({ id: slug(n), name: n })),
});

