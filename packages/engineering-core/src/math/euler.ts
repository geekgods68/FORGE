import type { Quat, Vec3 } from '../transform';

/**
 * Intrinsic XYZ Euler angles (radians), the same convention as three.js's default
 * 'XYZ' order. Used only at the UI boundary: the authoritative rotation is always
 * the unit quaternion, so display rounding never feeds back into stored state.
 */
export function quatFromEulerXYZ([x, y, z]: Vec3): Quat {
  const c1 = Math.cos(x / 2),
    c2 = Math.cos(y / 2),
    c3 = Math.cos(z / 2);
  const s1 = Math.sin(x / 2),
    s2 = Math.sin(y / 2),
    s3 = Math.sin(z / 2);
  return [
    s1 * c2 * c3 + c1 * s2 * s3,
    c1 * s2 * c3 - s1 * c2 * s3,
    c1 * c2 * s3 + s1 * s2 * c3,
    c1 * c2 * c3 - s1 * s2 * s3,
  ];
}

export function eulerXYZFromQuat([x, y, z, w]: Quat): Vec3 {
  // Rotation-matrix elements needed for the XYZ order.
  const m11 = 1 - 2 * (y * y + z * z);
  const m12 = 2 * (x * y - z * w);
  const m13 = 2 * (x * z + y * w);
  const m22 = 1 - 2 * (x * x + z * z);
  const m23 = 2 * (y * z - x * w);
  const m32 = 2 * (y * z + x * w);
  const m33 = 1 - 2 * (x * x + y * y);
  const ey = Math.asin(Math.max(-1, Math.min(1, m13)));
  if (Math.abs(m13) < 0.9999999) {
    return [Math.atan2(-m23, m33), ey, Math.atan2(-m12, m11)];
  }
  return [Math.atan2(m32, m22), ey, 0]; // gimbal lock
}
